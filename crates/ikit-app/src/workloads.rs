use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;

use ikit_core::workload::is_env;
use ikit_core::{Category, ServiceInstance, Workload};
use serde::Serialize;

use crate::{App, AppError, Result};

/// First line of every generated workload spec.
pub const SPEC_HEADER: &str = "# Generated by ikit from its state database. Edits here are not read back yet; use ikit commands.\n";

#[derive(Debug, Clone, Serialize)]
pub struct WorkloadDetail {
    pub org: String,
    #[serde(flatten)]
    pub workload: Workload,
    pub services: Vec<ServiceInstance>,
    pub spec_file: PathBuf,
}

/// `workloads/<name>.yaml`.
#[derive(Serialize)]
struct SpecFile<'a> {
    org: &'a str,
    name: &'a str,
    env: &'a str,
    target: &'a str,
    #[serde(skip_serializing_if = "BTreeMap::is_empty")]
    groups: BTreeMap<Category, Vec<SpecService<'a>>>,
}

#[derive(Serialize)]
struct SpecService<'a> {
    name: &'a str,
    service: &'a str,
    version: String,
    resolved: String,
    image: &'a str,
    #[serde(skip_serializing_if = "BTreeMap::is_empty")]
    env: &'a BTreeMap<String, String>,
    #[serde(skip_serializing_if = "<[String]>::is_empty")]
    secrets: &'a [String],
}

fn not_found(name: &str) -> AppError {
    AppError::NotFound(format!("workload `{name}`"))
}

impl App {
    /// Creates `wl-{env}-{nnn}` on `target` and makes it the active workload.
    pub async fn workload_create(&self, env: &str, target: &str) -> Result<Workload> {
        let config = self.config()?;
        if !is_env(env) || !config.envs.iter().any(|e| e == env) {
            return Err(AppError::Invalid(format!(
                "unknown env `{env}` (configured: {}; edit {} to add one)",
                config.envs.join(", "),
                self.org.config_file().display()
            )));
        }
        let target = self.target_show(target).await?;
        let workload = self
            .store
            .workloads()
            .create(&config.prefix, env, target.id)
            .await?;
        self.write_spec(&workload.name).await?;
        self.set_current_workload(Some(&workload.name))?;
        Ok(workload)
    }

    pub async fn workload_list(&self, env: Option<&str>) -> Result<Vec<Workload>> {
        Ok(self.store.workloads().list(env).await?)
    }

    pub async fn workload_get(&self, name: &str) -> Result<Workload> {
        self.store
            .workloads()
            .get(name)
            .await?
            .ok_or_else(|| not_found(name))
    }

    pub async fn workload_show(&self, name: &str) -> Result<WorkloadDetail> {
        let workload = self.workload_get(name).await?;
        let services = self.store.workloads().services(workload.id).await?;
        Ok(WorkloadDetail {
            org: self.org.name.clone(),
            spec_file: self.org.workload_spec(&workload.name),
            workload,
            services,
        })
    }

    pub async fn workload_use(&self, name: &str) -> Result<Workload> {
        let workload = self.workload_get(name).await?;
        self.set_current_workload(Some(&workload.name))?;
        Ok(workload)
    }

    /// Removes a workload definition, its keychain secrets and its spec file.
    pub async fn workload_remove(&self, name: &str) -> Result<()> {
        let detail = self.workload_show(name).await?;
        if detail.workload.status != ikit_core::WorkloadStatus::Draft {
            return Err(AppError::Invalid(format!(
                "{name} is {}; tear it down first with `ikit destroy --wl {name}`",
                detail.workload.status
            )));
        }
        for key in self.hook_secret_keys(name).await? {
            self.secrets.delete(&key)?;
        }
        for s in detail.services.iter().filter(|s| !s.secret_env.is_empty()) {
            self.secrets
                .delete(&self.service_secret_key(name, &s.name))?;
        }
        self.store.workloads().delete(name).await?;
        match fs::remove_file(&detail.spec_file) {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => return Err(e.into()),
            _ => {}
        }
        if self.current_workload()?.as_deref() == Some(name) {
            self.set_current_workload(None)?;
        }
        Ok(())
    }

    /// Rewrites `workloads/<name>.yaml` from the state database.
    pub(crate) async fn write_spec(&self, name: &str) -> Result<()> {
        let detail = self.workload_show(name).await?;
        let mut groups: BTreeMap<Category, Vec<SpecService>> = BTreeMap::new();
        for s in &detail.services {
            groups.entry(s.group).or_default().push(SpecService {
                name: &s.name,
                service: &s.registry_service,
                version: s.constraint.to_string(),
                resolved: s.version.to_string(),
                image: &s.image,
                env: &s.env,
                secrets: &s.secret_env,
            });
        }
        let w = &detail.workload;
        let spec = SpecFile {
            org: &self.org.name,
            name: &w.name,
            env: &w.env,
            target: &w.target,
            groups,
        };
        let yaml = serde_yaml_ng::to_string(&spec).expect("spec serializes");
        if let Some(dir) = detail.spec_file.parent() {
            fs::create_dir_all(dir)?;
        }
        fs::write(&detail.spec_file, format!("{SPEC_HEADER}{yaml}"))?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use ikit_core::Connection;

    use super::*;
    use crate::testing::app;

    #[tokio::test]
    async fn create_use_and_remove() {
        let (_dir, app, _) = app().await;
        app.target_attach("laptop", Connection::Local)
            .await
            .unwrap();

        let wl = app.workload_create("dev", "laptop").await.unwrap();
        assert_eq!(wl.name, "wl-acme-dev-001");
        assert_eq!(
            app.current_workload().unwrap().as_deref(),
            Some("wl-acme-dev-001")
        );
        let spec = fs::read_to_string(app.org().workload_spec("wl-acme-dev-001")).unwrap();
        assert!(
            spec.starts_with(SPEC_HEADER) && spec.contains("target: laptop"),
            "{spec}"
        );

        assert!(matches!(
            app.workload_create("nope", "laptop").await,
            Err(AppError::Invalid(_))
        ));
        assert!(matches!(
            app.workload_create("dev", "missing").await,
            Err(AppError::NotFound(_))
        ));

        app.workload_remove("wl-acme-dev-001").await.unwrap();
        assert_eq!(app.current_workload().unwrap(), None);
        assert!(!app.org().workload_spec("wl-acme-dev-001").exists());
        assert_eq!(
            app.workload_create("dev", "laptop").await.unwrap().name,
            "wl-acme-dev-002"
        );
    }

    #[tokio::test]
    async fn target_with_workloads_cannot_be_detached() {
        let (_dir, app, _) = app().await;
        app.target_attach("laptop", Connection::Local)
            .await
            .unwrap();
        app.workload_create("dev", "laptop").await.unwrap();
        match app.target_detach("laptop").await {
            Err(AppError::InUse { by, .. }) => assert_eq!(by, ["wl-acme-dev-001"]),
            other => panic!("{other:?}"),
        }
    }
}
